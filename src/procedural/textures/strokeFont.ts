/**
 * Layout text into positioned polylines with per-glyph wobble.
 */
export function layoutText(text: string, options: LayoutOptions = {}): TextLayoutResult {
  const size = options.size ?? 48;
  const tracking = options.tracking ?? 0.15;
  const wobble = options.wobble ?? 0.05;
  const defaultSeed = options.seed ?? hashString(`${text}|${size}|${tracking}|${wobble}`);
  const seededRng = new Rng(defaultSeed);
  const rng = options.rng ?? seededRng.next.bind(seededRng);

  const polylines: Polyline[] = [];
  let curX = 0;
  const charAdvance = size * (1.0 + tracking);

  for (let i = 0; i < text.length; i++) {
    const rawChar = text[i]!;
    const char = rawChar.toUpperCase();
    const glyph = GLYPHS[char] ?? GLYPHS['?']!;

    const rot = (rng() * 2.0 - 1.0) * wobble;
    const dy = (rng() * 2.0 - 1.0) * wobble * size;
    const scaleY = 1.0 + (rng() * 2.0 - 1.0) * wobble * 0.5;

    const cosR = Math.cos(rot);
    const sinR = Math.sin(rot);

    for (const stroke of glyph) {
      const transformedStroke: Point2D[] = [];
      for (const [gx, gy] of stroke) {
        // Center around (0.5, 0.5) for local glyph rotation
        const lx = (gx - 0.5) * size;
        const ly = (gy - 0.5) * size * scaleY;

        const rx = lx * cosR - ly * sinR;
        const ry = lx * sinR + ly * cosR;

        const px = curX + rx + size * 0.5;
        const py = ry + size * 0.5 + dy;
        transformedStroke.push([px, py]);
      }
      polylines.push(transformedStroke);
    }

    curX += charAdvance;
  }

  return {
    polylines,
    width: Math.max(size, curX),
    height: size * 1.4,
  };
}
