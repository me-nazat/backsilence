#!/usr/bin/env node
/* Emits reports/world/natatorium_vs_footage.md. Every "game" cell is computed from the
 * live layout/config/theme modules (run with vite-node). Reference cells cite
 * reference/video/notes.md frames. Exit 1 on any unmeasured cell or unexplained delta > 15 %. */
import { writeFileSync, mkdirSync } from 'node:fs';
import { WORLD } from '../../src/app/Config.ts';
import { NatatoriumMap } from '../../src/world/maps/NatatoriumMap.ts';
import { layoutText } from '../../src/procedural/textures/strokeFont.ts';
import { readFileSync } from 'node:fs';
import { SECTOR_THEMES } from '../../src/procedural/textures/TileMaterialFactory.ts';

const layout = NatatoriumMap.generateLayout({ seed: 1, difficulty: 'normal', playerCount: 1 });
const fogProfile = NatatoriumMap.atmosphere?.fog ?? { density: NaN, color: '?' };
const rows = [];
const add = (frame, prop, ref, game, tol, explain = '') => rows.push({ frame, prop, ref, game, tol, explain });

const wallTop = (id) => layout.walls.find((w) => w.id === id)?.max.y;
const hallCeil = Math.max(...layout.walls.filter((w) => w.id.startsWith('wall_outer')).map((w) => w.max.y));
const foyerCeil = layout.walls.find((w) => w.id === 'wall_spawn_tagline')?.max.y;
const arch = layout.walls.find((w) => w.id === 'wall_arch1_lintel');
const archW = arch ? arch.max.x - arch.min.x : NaN;
const archH = arch ? arch.min.y : NaN;
const slab = layout.platforms.find((p) => p.id === 'plat_foyer');
const pil = layout.pillars.find((p) => p.id === 'pil_dry_room_2');
const trench = layout.platforms.filter((p) => p.id.startsWith('plat_trench'));
const trenchW = trench.length === 2
  ? Math.min(...trench.map((p) => p.rect[0])) === trench[0].rect[0]
    ? trench[1].rect[0] - trench[0].rect[2]
    : trench[0].rect[0] - trench[1].rect[2]
  : NaN;
const fogT = (d) => Math.exp(-((d * fogProfile.density) ** 2));
const theme = SECTOR_THEMES.natatorium;
const hex = (h) => parseInt(h.slice(1), 16);
const hexDelta = (a, b) => {
  const ca = [hex(a) >> 16, (hex(a) >> 8) & 255, hex(a) & 255];
  const cb = [hex(b) >> 16, (hex(b) >> 8) & 255, hex(b) & 255];
  return Math.max(...ca.map((v, i) => Math.abs(v - cb[i]))) / 255;
};

add('f_004-009', 'Hall vault ceiling height (m)', 9.0, hallCeil, 0.15);
add('f_013-015', 'Foyer ceiling height (m)', 6.0, foyerCeil, 0.15);
add('f_004-009', 'Arch opening width (m)', 6.5, archW, 0.15);
add('f_004-009', 'Arch opening height (m)', 6.0, archH, 0.15);
add('f_004-009', 'Slab top Y above water (m)', 0.30, slab?.topY, 0.15);
add('f_035-036', 'Slab exposed thickness (m)', 0.30, slab ? slab.topY - 0 : NaN, 0.15);
add('f_035-036', 'Tile pitch (m)', 0.15, WORLD.TILE_METERS, 0.03);
add('f_013-015', 'Pillar diameter (m)', 1.5, pil ? pil.radius * 2 : NaN, 0.15);
const glyph = layoutText('2', { size: 380, tracking: 0.08, wobble: 0.04, seed: 102 });
const ys = glyph.polylines.flat().map((pt) => pt[1]);
const glyphPx = Math.max(...ys) - Math.min(...ys);
add('f_013-015', 'Spray numeral height (m)', 0.5, pil ? glyphPx * (pil.decalWidth / 512) : NaN, 0.15);
const derived = JSON.parse(readFileSync('reference/derived_targets.json', 'utf8'));
const refFog = derived.categories.horizon_haze.fogRegion.meanRGB.map((v) => Math.round(v * 255));
const toHex = (c) => '#' + c.map((v) => v.toString(16).padStart(2, '0')).join('');
add('f_008,f_025', 'Horizon fog colour max-channel delta vs derived horizon_haze ' + toHex(refFog), 0, hexDelta(toHex(refFog), fogProfile.color), 0.15);
const gaps = [10, 20, 30, 40].map((d) => ({ d, t: fogT(d) }));
add('f_018-020', 'Water depth over cracked floor (m)', 0.75, layout.waterBodies[0].waterY - layout.waterBodies[0].floorY, 0.15);
add('f_035-036', 'Trench width (m)', 1.05, trenchW, 0.15);
add('f_004-009', 'Camera height above slab top (m)', 1.65, WORLD.PLAYER.EYE_STAND, 0.15);
add('f_001', 'Platform-top colour max-channel delta', 0, hexDelta(theme.platformTop.base, '#c29a56'), 0.05);
add('f_001', 'Wall colour max-channel delta', 0, hexDelta(theme.wall.base, '#c8b580'), 0.05);
add('f_018', 'Pool floor colour max-channel delta', 0, hexDelta(theme.poolFloor.base, '#cbba8b'), 0.05);

let bad = 0;
const lines = ['# Natatorium vs footage', '', '_Generated by `scripts/world/measure-natatorium.mjs`; do not edit._', '',
  '| Frame | Property | Reference | Game | Delta | Action |', '|---|---|---|---|---|---|'];
for (const r of rows) {
  const ok = Number.isFinite(r.game);
  const delta = !ok ? NaN : r.ref === 0 ? r.game : Math.abs(r.game - r.ref) / Math.abs(r.ref);
  const pass = ok && delta <= r.tol;
  if (!ok || !pass) bad++;
  const f = (v) => (Number.isFinite(v) ? Number(v.toFixed(3)) : 'UNMEASURED');
  lines.push(`| ${r.frame} | ${r.prop} | ${r.ref} | ${f(r.game)} | ${r.ref === 0 ? f(delta) : f(delta * 100) + ' %'} | ${pass ? 'match' : r.explain ? 'explained: ' + r.explain : 'FIX'} |`);
}
lines.push('', '## Known gaps (not measurable from the 37 reference frames)', '',
  'The frames contain no calibrated distances, so a reference fog transmittance at 10/20/30/40 m cannot be derived without inventing numbers. Game values are emitted for the record; the constraint is the qualitative f_025 spec (*water reaches the horizon with no visible edge*), enforced by the height-fog work in Prompt 7 D.', '',
  '| Distance | Game transmittance (FogExp2) |', '|---|---|', ...gaps.map((g) => `| ${g.d} m | ${g.t.toFixed(3)} |`));
mkdirSync('reports/world', { recursive: true });
writeFileSync('reports/world/natatorium_vs_footage.md', lines.join('\n') + '\n');
console.log(lines.join('\n'));
if (bad) { console.error(`${bad} row(s) unmeasured or out of tolerance`); process.exit(1); }
